import SwiftUI
import AVFoundation
import PersonaPlex

@main
struct PersonaPlexMacApp: App {
    init() {
        // Headless A/B: measures the Swift path the same way the Python harness
        // measures the Python path, so the two quantizations can be compared
        // without a microphone or a human in the loop.
        //
        //   PersonaPlexMac --bench <input.wav> [steps]
        if let i = CommandLine.arguments.firstIndex(of: "--bench") {
            let wav = CommandLine.arguments.count > i + 1 ? CommandLine.arguments[i + 1] : ""
            let steps = CommandLine.arguments.count > i + 2
                ? Int(CommandLine.arguments[i + 2]) ?? 150 : 150
            Task {
                await Bench.run(wavPath: wav, steps: steps)
                exit(0)
            }
            RunLoop.current.run(until: Date(timeIntervalSinceNow: 1800))
        }
    }

    var body: some Scene {
        WindowGroup("PersonaPlex") {
            PersonaPlexView()
        }
        .defaultSize(width: 640, height: 760)
    }
}

enum Bench {
    static func run(wavPath: String, steps: Int) async {
        guard let audio = loadWav(wavPath) else {
            print("could not read wav: \(wavPath)")
            return
        }
        print("input: \(wavPath)  \(String(format: "%.2f", Double(audio.count) / 24000))s"
              + "  generating \(steps) steps\n")
        print("prec     load_s     warm_s     infer_s    ms/step")

        for p in ModelPrecision.allCases {
            guard let dir = PersonaPlexViewModel.localSnapshot(for: p.modelId) else {
                print("\(p.rawValue): no local snapshot — run mlxmgr install first")
                continue
            }
            PersonaPlexViewModel.boundMLXCache()
            PersonaPlexViewModel.linkLibraryCache(modelId: p.modelId, to: dir)
            do {
                let t0 = CFAbsoluteTimeGetCurrent()
                let m = try await PersonaPlexModel.fromPretrained(
                    modelId: p.modelId, cacheDir: dir, offlineMode: true
                )
                let loadT = CFAbsoluteTimeGetCurrent() - t0

                let t1 = CFAbsoluteTimeGetCurrent()
                m.warmUp()
                let warmT = CFAbsoluteTimeGetCurrent() - t1

                // Warmup already compiled the kernels, so this run is steady-state.
                let t2 = CFAbsoluteTimeGetCurrent()
                let (out, textTokens) = m.respond(userAudio: audio, maxSteps: steps)
                let inferT = CFAbsoluteTimeGetCurrent() - t2

                let msStep = inferT * 1000 / Double(steps)
                print(p.rawValue.padding(toLength: 8, withPad: " ", startingAt: 0)
                      + String(format: "%9.1f  %9.1f  %10.1f  %9.1f",
                               loadT, warmT, inferT, msStep))
                print("   -> \(out.count) samples ("
                      + String(format: "%.1f", Double(out.count) / 24000) + "s), "
                      + "\(textTokens.count) text tokens")
                // Hand the weights back before loading the next precision.
                // Without this the two models stack in MLX's pool and the
                // second load can OOM the GPU.
                PersonaPlexViewModel.releaseModel(m)
            } catch {
                print("\(p.rawValue): FAILED \(error)")
            }
        }
        print("\nbudget is 80 ms/step (12.5 Hz frames); under that = real-time")
    }

    /// Minimal 24 kHz mono wav reader — the bench inputs are generated by our
    /// own script, so there is no need for a general decoder.
    static func loadWav(_ path: String) -> [Float]? {
        guard let file = try? AVAudioFile(forReading: URL(fileURLWithPath: path)) else {
            return nil
        }
        let fmt = AVAudioFormat(commonFormat: .pcmFormatFloat32,
                                sampleRate: 24000, channels: 1, interleaved: false)!
        guard let conv = AVAudioConverter(from: file.processingFormat, to: fmt) else {
            return nil
        }
        let capacity = AVAudioFrameCount(
            Double(file.length) * 24000 / file.processingFormat.sampleRate + 4096)
        guard let out = AVAudioPCMBuffer(pcmFormat: fmt, frameCapacity: capacity) else {
            return nil
        }
        var done = false
        var err: NSError?
        conv.convert(to: out, error: &err) { _, status in
            if done { status.pointee = .endOfStream; return nil }
            let inBuf = AVAudioPCMBuffer(pcmFormat: file.processingFormat,
                                         frameCapacity: AVAudioFrameCount(file.length))!
            try? file.read(into: inBuf)
            done = true
            status.pointee = .haveData
            return inBuf
        }
        if err != nil { return nil }
        guard let ch = out.floatChannelData?[0] else { return nil }
        return Array(UnsafeBufferPointer(start: ch, count: Int(out.frameLength)))
    }
}
